import logging

logger = logging.getLogger(__name__)

def get_code_analysis_prompt(code: str, file_name: str = "", user_question: str = "") -> str:
    """
    يبني مطالبة (Prompt) متخصصة لتحليل الأكواد البرمجية بناءً على أفضل الممارسات.
    """
    # تحديد اللغة من امتداد الملف
    ext = file_name.split('.')[-1] if '.' in file_name else 'txt'
    lang_map = {
        'py': 'Python', 'js': 'JavaScript', 'ts': 'TypeScript', 'java': 'Java',
        'cpp': 'C++', 'c': 'C', 'cs': 'C#', 'go': 'Go', 'rs': 'Rust',
        'php': 'PHP', 'rb': 'Ruby', 'swift': 'Swift', 'kt': 'Kotlin',
        'html': 'HTML', 'css': 'CSS', 'json': 'JSON', 'sql': 'SQL'
    }
    language = lang_map.get(ext, 'code')
    
    if user_question:
        base_prompt = f"""
        أنت خبير برمجي متخصص في تحليل وشرح الأكواد البرمجية. أجب عن السؤال التالي بناءً على الكود المقدم.

        **لغة البرمجة**: {language}
        **السؤال**: {user_question}

        **الكود**:
        ---
        {code}
        ---

        أجب بدقة واحترافية. إذا كان السؤال يتطلب تعديلاً على الكود، قدم الكود المعدل داخل علامات Markdown مناسبة (```{ext} ... ```).
        """
    else:
        base_prompt = f"""
        أنت خبير برمجي متخصص في تحليل الأكواد البرمجية. قم بتحليل الكود التالي تحليلاً شاملاً واحترافياً.

        **لغة البرمجة**: {language}
        **اسم الملف**: {file_name if file_name else 'غير معروف'}

        **الكود**:
        ---
        {code}
        ---

        قدم تحليلك المنظم كما يلي:
        1. **🎯 الغرض العام**: شرح موجز (2-3 أسطر) عن وظيفة هذا الكود.
        2. **⚙️ تحليل المكونات الرئيسية**: شرح لأهم الدوال (functions)، الأصناف (classes)، والمتغيرات.
        3. **🐞 اكتشاف الأخطاء والمشاكل المحتملة**: حدد أي أخطاء منطقية، ثغرات أمنية، أو مشاكل في الأداء.
        4. **💡 اقتراحات للتحسين**: قدم نصائح عملية لتحسين الكود (مثل: أفضل الممارسات، تحسين الأداء، تبسيط المنطق).
        5. **📝 توثيق مقترح**: قدم مثالاً على `docstring` مناسباً للدالة الرئيسية في الكود.

        استخدم لغة عربية واضحة ومهنية. ضع أي كود برمجي داخل علامات Markdown مناسبة.
        """
    return base_prompt
